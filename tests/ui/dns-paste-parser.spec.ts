import { expect, test } from "@playwright/test";
import { parseDnsPaste } from "../../src/features/domains/parseDnsPaste";
import { normalizeDnsHost } from "../../src/features/domains/dnsHost";

test("DNS shorthand infers addresses, targets and verification records", () => {
  expect(parseDnsPaste("www 192.168.3.2", "example.test")[0]).toMatchObject({ type: "A", rr: "www", value: "192.168.3.2" });
  expect(parseDnsPaste("A 192.168.3.2")[0]).toMatchObject({ type: "A", value: "192.168.3.2" });
  expect(parseDnsPaste("MX 10 mx.example.net")[0]).toMatchObject({ type: "MX", priority: 10, value: "mx.example.net" });
  expect(parseDnsPaste("api.example.test -> 2001:db8::1", "example.test")[0]).toMatchObject({ type: "AAAA", rr: "api", value: "2001:db8::1" });
  expect(parseDnsPaste("www 指向 target.example.net", "example.test")[0]).toMatchObject({ type: "CNAME", rr: "www", value: "target.example.net", inference: expect.any(String) });
  expect(parseDnsPaste("_acme-challenge abc123", "example.test")[0]).toMatchObject({ type: "TXT", rr: "_acme-challenge", value: "abc123" });
  expect(parseDnsPaste("v=DMARC1; p=none")[0]).toMatchObject({ type: "TXT", rr: "_dmarc" });
  expect(parseDnsPaste("v=spf1 include:example.net ~all")[0]).toMatchObject({ type: "TXT", rr: "@" });
  expect(parseDnsPaste("@ 10 mx.example.net")[0]).toMatchObject({ type: "MX", rr: "@", priority: 10, value: "mx.example.net" });
  expect(parseDnsPaste('_sip._tcp 10 5 443 service.example.net')[0]).toMatchObject({ type: "SRV", rr: "_sip._tcp" });
  expect(parseDnsPaste('@ 0 issue "letsencrypt.org"')[0]).toMatchObject({ type: "CAA", rr: "@" });
  expect(() => parseDnsPaste("www ::::")).toThrow();
});

test("DNS host normalization extracts only the current zone from full names and URLs", () => {
  expect(normalizeDnsHost("https://www.example.test/path?q=1", "example.test")).toBe("www");
  expect(normalizeDnsHost("EXAMPLE.TEST.", "example.test")).toBe("@");
  expect(normalizeDnsHost("*.example.test", "example.test")).toBe("*");
  expect(normalizeDnsHost("_acme-challenge.example.test", "example.test")).toBe("_acme-challenge");
  expect(normalizeDnsHost("api.dev", "example.test")).toBe("api.dev");
  expect(() => normalizeDnsHost("https://example.test.foreign.test/path", "example.test")).toThrow(/不属于当前域名/);
  expect(() => normalizeDnsHost("https://notexample.test", "example.test")).toThrow(/不属于当前域名/);
});

test("DNS paste handles labeled instructions, zone records and JSON without corrupting TXT", () => {
  expect(parseDnsPaste("主机记录: www.example.test\n记录类型: CNAME\n记录值: target.example.net\nTTL: 900\n解析线路: 默认", "example.test")).toEqual([{ type: "CNAME", rr: "www", value: "target.example.net", ttl: 900, line: "default" }]);
  expect(parseDnsPaste('@ 3600 IN MX 10 mx.example.test.\n_acme-challenge IN TXT "first " "second"', "example.test")).toEqual([{ type: "MX", rr: "@", value: "mx.example.test.", ttl: 3600, priority: 10 }, { type: "TXT", rr: "_acme-challenge", value: "first second" }]);
  expect(parseDnsPaste('{"Type":"TXT","RR":"@","Value":"v=spf1 include:example.test ~all"}')[0].value).toBe("v=spf1 include:example.test ~all");
  expect(parseDnsPaste("2001:db8::1")[0]).toMatchObject({ type: "AAAA", value: "2001:db8::1" });
  expect(parseDnsPaste("192.0.2.10")[0].rr).toBeUndefined();
  expect(() => parseDnsPaste("www A 999.0.0.1")).toThrow();
  expect(() => parseDnsPaste("www.foreign.test. IN A 192.0.2.10", "example.test")).toThrow(/不属于当前域名/);
  expect(() => parseDnsPaste('{"type":"MX","rr":"@","value":"mx.example.test","priority":99}')).toThrow(/优先级/);
  expect(() => parseDnsPaste("这是一段不含记录的说明")).toThrow(/未识别/);
});

test("DNS paste fills the editor locally and retains values when parsing fails", async ({ page }) => {
  let writes = 0;
  await page.route("**/api/accounts**", route => route.fulfill({ json: [{ id: 7, account_name: "Fixture DNS", cloud_type: "aliyun", access_key_id: "test-only-id", enabled: true, sort_order: 0, created_at: 1, updated_at: 1 }] }));
  await page.route("**/api/local-assets**", route => route.fulfill({ json: [{ account_id: 7, resource_type: "domain", asset_key: "example.test", payload: { DomainName: "example.test" }, fetched_at: 1 }] }));
  await page.route("**/api/dns-records**", route => { if (route.request().method() !== "GET") writes++; return route.fulfill({ json: { items: [], total: 0 } }); });
  await page.goto("/");
  await page.getByRole("button", { name: "资产管理", exact: true }).click();
  await page.getByRole("button", { name: "解析管理", exact: true }).click();
  await page.getByRole("button", { name: /添加记录/ }).click();
  const editor = page.getByRole("dialog", { name: "添加解析记录", exact: true });
  const paste = editor.getByLabel("粘贴 DNS 记录或配置说明", { exact: true });
  const parse = editor.getByRole("button", { name: "智能解析", exact: true });
  await paste.fill("192.168.3.2\n127.0.0.1");
  await parse.click();
  await expect(editor.getByLabel("记录类型", { exact: true })).toHaveValue("A");
  await expect(editor.getByLabel("主机记录", { exact: true })).toHaveValue("@");
  await expect(editor.locator(".dns-parse-success")).toContainText("原文未提供主机，暂填根域名 @");
  await editor.getByLabel("选择要填入的记录", { exact: true }).selectOption("1");
  await expect(editor.getByLabel("记录值", { exact: true })).toHaveValue("127.0.0.1");
  await editor.getByLabel("主机记录", { exact: true }).fill("api");
  await paste.fill("2001:db8::1");
  await parse.click();
  await expect(editor.getByLabel("记录类型", { exact: true })).toHaveValue("AAAA");
  await expect(editor.getByLabel("主机记录", { exact: true })).toHaveValue("api");
  await expect(editor.locator(".dns-parse-success")).toContainText("沿用已填写的 api");
  await paste.fill("主机记录: www.example.test\n记录类型: CNAME\n记录值: target.example.net\nTTL: 900");
  await parse.click();
  await expect(editor.getByLabel("主机记录", { exact: true })).toHaveValue("www");
  await expect(editor.getByLabel("记录值", { exact: true })).toHaveValue("target.example.net");
  await expect(editor.getByLabel("记录类型", { exact: true })).toHaveValue("CNAME");
  await expect(editor.getByLabel("TTL", { exact: true })).toHaveValue("900");
  await expect(editor.locator("#dns-value-help")).toContainText("不要加 http:// 或路径");
  await paste.fill('@ 3600 IN MX 10 mx.example.test\n_acme-challenge IN TXT "first " "second"');
  await parse.click();
  await expect(editor.getByLabel("MX 优先级", { exact: true })).toHaveValue("10");
  await editor.getByLabel("选择要填入的记录", { exact: true }).selectOption("1");
  await expect(editor.getByLabel("记录类型", { exact: true })).toHaveValue("TXT");
  await expect(editor.getByLabel("记录值", { exact: true })).toHaveValue("first second");
  const host = editor.getByLabel("主机记录", { exact: true });
  await editor.getByRole("button", { name: "根域名 @", exact: true }).click();
  await expect(host).toHaveValue("@");
  await expect(editor.locator(".dns-host-preview")).toHaveText("完整域名：example.test");
  await editor.getByRole("button", { name: "泛域名 *", exact: true }).click();
  await expect(host).toHaveValue("*");
  await expect(editor.locator(".dns-host-preview")).toHaveText("完整域名：*.example.test");
  await editor.getByRole("button", { name: "证书验证", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(host).toHaveValue("_acme-challenge");
  await expect(editor.getByLabel("记录值", { exact: true })).toHaveValue("first second");
  await host.fill("https://api.example.test/service");
  await editor.getByLabel("记录值", { exact: true }).focus();
  await expect(host).toHaveValue("api");
  await expect(editor.locator(".dns-host-preview")).toHaveText("完整域名：api.example.test");
  await host.fill("https://foreign.test/path");
  await editor.getByLabel("记录值", { exact: true }).focus();
  await expect(editor.locator(".dns-host-error")).toContainText("不属于当前域名");
  await expect(host).toHaveValue("https://foreign.test/path");
  await editor.getByRole("button", { name: "网站 www", exact: true }).click();
  await expect(host).toHaveValue("www");
  await expect(editor.locator(".dns-host-error")).toHaveCount(0);
  await paste.fill("无法识别的内容");
  await parse.click();
  await expect(editor.getByRole("alert")).toContainText("未识别");
  await expect(editor.getByLabel("记录值", { exact: true })).toHaveValue("first second");
  expect(writes).toBe(0);
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await editor.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    const box = await editor.boundingBox();
    expect(box!.width).toBeLessThanOrEqual(width);
    if (width === 1440) expect(box!.width).toBeGreaterThan(700);
  }
  await paste.fill("主机记录: _acme-challenge\n记录类型: TXT\n记录值: 示例验证文本");
  await parse.click();
  await editor.screenshot({ path: "test-results/dns-paste-editor.png" });
  await editor.getByRole("button", { name: "关闭解析记录编辑", exact: true }).click();
  await expect(editor).toHaveCount(0);
});
