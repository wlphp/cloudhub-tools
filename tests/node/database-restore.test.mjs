import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import http from "node:http";
import { once } from "node:events";
import { DatabaseSync } from "node:sqlite";
import { test } from "node:test";

test("browser restore uses native selective import, preserves local key/settings and snapshots before writes", async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "cloudhub-browser-restore-"));
  const previous = process.env.LOCALAPPDATA;
  process.env.LOCALAPPDATA = root;
  const { handleDatabaseMigrationRoutes } = await import("../../web-api/core/database-migration.mjs");
  const { callDatabaseRestore, closeDatabaseRestoreBridge, createBrowserCloudBackup } = await import("../../web-api/services/database-restore.mjs");
  if (previous === undefined) delete process.env.LOCALAPPDATA; else process.env.LOCALAPPDATA = previous;
  const dir = path.join(root, "CloudHubTools");
  t.after(async () => {
    closeDatabaseRestoreBridge();
    // The helper exits asynchronously on Windows; retry only its test directory.
    await fs.promises.rm(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 100 });
  });
  await callDatabaseRestore({ op: "cancel", token: "unused" }); // initializes an isolated native schema
  const dbPath = path.join(dir, "cloudhub_tools.sqlite3");
  let db = new DatabaseSync(dbPath);
  db.exec("INSERT INTO memo_groups(name,sort_order,created_at) VALUES('fixture',0,1)");
  db.exec("INSERT INTO memo_notes(title,body,group_name,created_at,updated_at) VALUES('incoming','fixture','fixture',1,1)");
  const sourcePath = path.join(dir, "fixture.sqlite3");
  db.prepare("VACUUM INTO ?").run(sourcePath);
  db.exec("DELETE FROM memo_notes; INSERT INTO memo_notes(title,body,group_name,created_at,updated_at) VALUES('local','fixture','fixture',1,1)");
  db.prepare("INSERT INTO client_preferences(key,value,updated_at) VALUES(?,?,1)").run("cloud.sync.preview.config", "keep-local-config");
  db.close();
  const localKey = crypto.randomBytes(32); fs.writeFileSync(path.join(dir, ".key"), localKey);
  const sourceKey = crypto.randomBytes(32);
  const nonce = crypto.randomBytes(12), cipher = crypto.createCipheriv("aes-256-gcm", sourceKey, nonce);
  const ciphertext = Buffer.concat([nonce, cipher.update("non-sensitive-fixture"), cipher.final(), cipher.getAuthTag()]).toString("base64");
  const source = new DatabaseSync(sourcePath);
  source.prepare("INSERT INTO cloud_accounts(account_name,cloud_type,access_key_id,secret_ciphertext,created_at,updated_at) VALUES('incoming-account','other','fixture-id',?,1,1)").run(ciphertext);
  source.close();
  const database = fs.readFileSync(sourcePath);
  const hash = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
  const manifest = Buffer.from(JSON.stringify({ format: "cloudhub-tools-database-migration", version: 1, exported_at: "2026-10-29", database_sha256: hash(database), key_sha256: hash(sourceKey) }));
  const length = Buffer.alloc(4); length.writeUInt32LE(manifest.length);
  const sizes = Buffer.alloc(12); sizes.writeBigUInt64LE(BigInt(database.length)); sizes.writeUInt32LE(32, 8);
  const bytes = Buffer.concat([Buffer.from("CHDBMIG1"), length, manifest, sizes, database, sourceKey]);
  let exclusive = false;
  const server = http.createServer((req, res) => {
    void handleDatabaseMigrationRoutes(req, res, new URL(req.url, "http://localhost"), (response, status, value) => { response.writeHead(status, { "Content-Type": "application/json" }); response.end(JSON.stringify(value)); }, { enter() { assert.equal(exclusive, false); exclusive = true; }, leave() { exclusive = false; } });
  });
  server.listen(0, "127.0.0.1"); await once(server, "listening");
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${server.address().port}/api/database-import/`;
  const post = (action, body) => fetch(base + action, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const preview = async () => {
    const response = await fetch(base + "preview", { method: "POST", body: bytes });
    assert.equal(response.status, 200, await response.clone().text());
    const result = await response.json();
    assert.equal(result.categories.find(item => item.table === "memo_notes").count, 1);
    assert.equal(JSON.stringify(result).includes(sourceKey.toString("base64")), false);
    assert.equal(JSON.stringify(result).includes("non-sensitive-fixture"), false);
    return result;
  };
  let prepared = await preview();
  db = new DatabaseSync(dbPath);
  assert.equal(db.prepare("SELECT title FROM memo_notes").get().title, "local"); db.close();
  assert.equal((await post("cancel", { token: prepared.token })).status, 200);
  assert.equal((await post("confirm", { token: prepared.token, tables: ["memo_notes"], mode: "replace", forceRestore: false })).status, 400);
  prepared = await preview();
  assert.equal((await post("confirm", { token: prepared.token, tables: ["operation_logs"], mode: "replace", forceRestore: false })).status, 400);
  prepared = await preview();
  const restored = await post("confirm", { token: prepared.token, tables: ["memo_notes"], mode: "replace", forceRestore: false });
  assert.equal(restored.status, 200, await restored.clone().text());
  assert.match(await restored.json(), /恢复完成/);
  assert.equal(exclusive, false);
  db = new DatabaseSync(dbPath);
  assert.equal(db.prepare("SELECT title FROM memo_notes").get().title, "incoming");
  assert.equal(db.prepare("SELECT count(*) AS n FROM cloud_accounts").get().n, 0);
  assert.equal(db.prepare("SELECT value FROM client_preferences WHERE key='cloud.sync.preview.config'").get().value, "keep-local-config");
  db.close();
  assert.deepEqual(fs.readFileSync(path.join(dir, ".key")), localKey);
  assert.ok(fs.readdirSync(dir).some(name => name.includes("before-import")));
  prepared = await preview();
  assert.equal((await post("confirm", { token: prepared.token, tables: ["cloud_accounts"], mode: "merge", forceRestore: false })).status, 200);
  db = new DatabaseSync(dbPath);
  const restoredCipher = db.prepare("SELECT secret_ciphertext FROM cloud_accounts").get().secret_ciphertext;
  db.close();
  const packed = Buffer.from(restoredCipher, "base64");
  const decipher = crypto.createDecipheriv("aes-256-gcm", localKey, packed.subarray(0, 12));
  decipher.setAuthTag(packed.subarray(-16));
  assert.equal(Buffer.concat([decipher.update(packed.subarray(12, -16)), decipher.final()]).toString(), "non-sensitive-fixture");
  assert.equal((await fetch(base + "preview", { method: "POST", body: "invalid" })).status, 400);
  const password = "non-sensitive-backup-fixture";
  const salt = crypto.randomBytes(16), iv = crypto.randomBytes(12);
  const header = Buffer.concat([Buffer.from("CHDBENC2"), salt, iv]);
  const backupKey = crypto.argon2Sync("argon2id", { message: password, nonce: salt, parallelism: 1, tagLength: 32, memory: 65536, passes: 3 });
  const seal = crypto.createCipheriv("aes-256-gcm", backupKey, iv); seal.setAAD(header);
  const encrypted = Buffer.concat([header, seal.update(bytes), seal.final(), seal.getAuthTag()]);
  assert.equal((await fetch(base + "preview", { method: "POST", body: encrypted })).status, 400);
  const protectedResponse = await fetch(base + "preview", { method: "POST", headers: { "X-Backup-Password": encodeURIComponent(password) }, body: encrypted });
  assert.equal(protectedResponse.status, 200, await protectedResponse.clone().text());
  const protectedPreview = await protectedResponse.json();
  assert.equal((await post("cancel", { token: protectedPreview.token })).status, 200);
  const localBackup = await createBrowserCloudBackup();
  const { validatePackage } = await import("../../web-api/services/cloud-sync.mjs");
  validatePackage(localBackup);
  const manifestLength = localBackup.readUInt32LE(8);
  const snapshotSize = Number(localBackup.readBigUInt64LE(12 + manifestLength));
  const localSnapshot = path.join(dir, "test-upload-snapshot.sqlite3");
  fs.writeFileSync(localSnapshot, localBackup.subarray(24 + manifestLength, 24 + manifestLength + snapshotSize));
  const uploaded = new DatabaseSync(localSnapshot);
  assert.equal(uploaded.prepare("SELECT title FROM memo_notes").get().title, "incoming");
  assert.equal(uploaded.prepare("SELECT count(*) AS n FROM cloud_accounts").get().n, 1);
  assert.equal(uploaded.prepare("SELECT count(*) AS n FROM client_preferences WHERE key LIKE 'cloud.sync.%'").get().n, 0);
  uploaded.close();
  assert.equal(fs.readdirSync(dir).some(name => name.startsWith(".browser-upload-")), false);
  await assert.rejects(callDatabaseRestore({ op: "backup", path: path.join(root, "outside.chdb") }));
  assert.equal(fs.existsSync(path.join(root, "outside.chdb")), false);
  assert.equal(fs.readdirSync(dir).some(name => name.startsWith(".browser-backup-") || name.startsWith(".cloudhub-import-preview-")), false);
});
