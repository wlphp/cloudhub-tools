#[cfg(windows)]
mod windows {
    use super::*;
    use std::{ffi::c_void, os::windows::io::AsRawHandle};
    type Handle = *mut c_void;
    #[repr(C)] #[derive(Default)] struct FileTime { low: u32, high: u32 }
    #[link(name = "kernel32")]
    extern "system" {
        fn CloseHandle(handle: Handle) -> i32;
        fn OpenProcess(access: u32, inherit: i32, pid: u32) -> Handle;
        fn GetLastError() -> u32;
        fn GetProcessTimes(process: Handle, created: *mut FileTime, exited: *mut FileTime, kernel: *mut FileTime, user: *mut FileTime) -> i32;
        fn GetExitCodeProcess(process: Handle, code: *mut u32) -> i32;
        fn QueryFullProcessImageNameW(process: Handle, flags: u32, path: *mut u16, length: *mut u32) -> i32;
        fn TerminateProcess(process: Handle, code: u32) -> i32;
        fn WaitForSingleObject(handle: Handle, milliseconds: u32) -> u32;
    }
    struct OwnedHandle(isize);
    impl OwnedHandle { fn raw(&self) -> Handle { self.0 as Handle } }
    impl Drop for OwnedHandle { fn drop(&mut self) { unsafe { CloseHandle(self.raw()); } } }
    /// Closing this handle also closes any surviving Chromium descendants.
    pub struct ProcessJob { _job: crate::core::codex::process::OwnedJob }
    impl ProcessJob {
        pub fn attach(child: &Child) -> PlatformResult<Self> {
            let job=crate::core::codex::process::OwnedJob::attach(child).map_err(|_|error("无法保护浏览器进程，已取消启动"))?;
            Ok(Self { _job: job })
        }
    }
    fn created(handle: Handle) -> PlatformResult<u64> {
        let mut birth=FileTime::default();let mut exited=FileTime::default();let mut kernel=FileTime::default();let mut user=FileTime::default();
        if unsafe { GetProcessTimes(handle,&mut birth,&mut exited,&mut kernel,&mut user) } == 0 { return Err(error("无法确认浏览器进程身份")); }
        Ok((birth.high as u64) << 32 | birth.low as u64)
    }
    pub fn child_created(child: &Child) -> PlatformResult<u64> { created(child.as_raw_handle()) }
    pub struct VerifiedProcess(OwnedHandle);
    impl VerifiedProcess {
        pub fn open(record: &ProcessRecord, expected: &Path) -> PlatformResult<Option<Self>> {
            unsafe {
                let raw = OpenProcess(0x1000 | 0x100000 | 0x0001,0,record.pid); // query, synchronize, terminate
                if raw.is_null() {
                    return if GetLastError() == 87 { Ok(None) } else { Err(error("无法检查遗留浏览器进程权限")) };
                }
                let process=Self(OwnedHandle(raw as isize));
                if !process.alive()? || created(process.0.raw())? != record.created { return Ok(None); }
                let mut buffer=vec![0u16;32768];let mut length=buffer.len() as u32;
                if QueryFullProcessImageNameW(process.0.raw(),0,buffer.as_mut_ptr(),&mut length)==0 { return Err(error("无法确认浏览器程序路径")); }
                let actual=PathBuf::from(String::from_utf16(&buffer[..length as usize]).map_err(|_|error("浏览器程序路径无效"))?);
                let actual=actual.canonicalize().map_err(|_|error("无法确认浏览器程序路径"))?;
                let expected=expected.canonicalize().map_err(|_|error("无法确认浏览器内核路径"))?;
                if !actual.to_string_lossy().eq_ignore_ascii_case(&expected.to_string_lossy()) { return Ok(None); }
                Ok(Some(process))
            }
        }
        pub fn alive(&self) -> PlatformResult<bool> {
            let mut code=0;
            if unsafe { GetExitCodeProcess(self.0.raw(),&mut code) } == 0 { return Err(error("无法检查浏览器退出状态")); }
            Ok(code==259)
        }
        pub fn terminate(&self) -> PlatformResult<()> {
            if unsafe { TerminateProcess(self.0.raw(),0) } == 0 { return Err(error("无法关闭遗留浏览器，请手动关闭对应窗口")); }
            if unsafe { WaitForSingleObject(self.0.raw(),5000) } != 0 { return Err(error("等待遗留浏览器退出超时")); }
            Ok(())
        }
    }
}

#[cfg(all(test,windows))]
mod tests {
    use super::*;
    #[test]
    #[ignore = "Requires CLOUDHUB_BROWSER_TEST_EXE pointing to the verified test browser"]
    fn recorded_process_requires_matching_birth_and_executable() {
        let executable=PathBuf::from(std::env::var_os("CLOUDHUB_BROWSER_TEST_EXE").expect("set browser path"));
        let dir=std::env::temp_dir().join(format!("cloudhub-identity-test-{}",uuid::Uuid::new_v4()));
        fs::create_dir(&dir).unwrap();
        let mut child=std::process::Command::new(&executable).arg(format!("--user-data-dir={}",dir.display()))
            .args(super::super::runtime::network_flags(None))
            .args(["--headless=new","--no-first-run","about:blank"]).stdin(std::process::Stdio::null()).stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).spawn().unwrap();
        let job=ProcessJob::attach(&child).unwrap();
        let mut record=ProcessRecord {pid:child.id(),created:windows::child_created(&child).unwrap(),kernel_version:kernel::VERSION.into()};
        assert!(windows::VerifiedProcess::open(&record,&executable).unwrap().is_some());
        record.created+=1;
        assert!(windows::VerifiedProcess::open(&record,&executable).unwrap().is_none());
        record.created-=1;
        assert!(windows::VerifiedProcess::open(&record,&std::env::current_exe().unwrap()).unwrap().is_none());
        drop(job);child.wait().unwrap();
        fs::remove_dir_all(dir).unwrap();
    }
}
