//! Windows ownership, crash cleanup and safe identification of a leftover child.
//! PIDs alone are never sufficient: creation time and executable must also match.
use super::{error, kernel, root, validate_id};
use crate::core::error::PlatformResult;
use serde::{Deserialize, Serialize};
use std::{fs, path::{Path, PathBuf}, process::Child};

#[derive(Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ProcessRecord { pid: u32, created: u64, kernel_version: String }
fn record_path(id: &str) -> PlatformResult<PathBuf> {
    validate_id(id)?;
    Ok(root()?.join("environments").join(id).join("cloudhub-process.json"))
}
pub fn record(id: &str, child: &Child, version: &str) -> PlatformResult<()> {
    let value = ProcessRecord { pid: child.id(), created: windows::child_created(child)?, kernel_version: version.into() };
    let path = record_path(id)?;
    let temporary = path.with_extension("tmp");
    fs::write(&temporary, serde_json::to_vec(&value).map_err(|_| error("无法记录浏览器进程"))?).map_err(|_| error("无法记录浏览器进程"))?;
    fs::rename(temporary, path).map_err(|_| error("无法记录浏览器进程"))
}
fn read_record(id: &str) -> PlatformResult<Option<ProcessRecord>> {
    let path = record_path(id)?;
    if !path.exists() { return Ok(None); }
    use std::io::Read;
    let mut bytes = Vec::new();
    fs::File::open(path).map_err(|_| error("无法检查遗留浏览器进程"))?.take(1025).read_to_end(&mut bytes).map_err(|_| error("无法检查遗留浏览器进程"))?;
    if bytes.len() > 1024 { return Err(error("浏览器进程记录无效，请检查环境资料")); }
    let record: ProcessRecord = serde_json::from_slice(&bytes).map_err(|_| error("浏览器进程记录无效，请检查环境资料"))?;
    if !kernel::known_version(&record.kernel_version) { return Err(error("浏览器进程使用未知内核，请先恢复相应版本")); }
    Ok(Some(record))
}
pub fn is_orphan(id: &str) -> PlatformResult<bool> {
    let Some(record) = read_record(id)? else { return Ok(false); };
    Ok(windows::VerifiedProcess::open(&record, &kernel::executable(&record.kernel_version)?)?.is_some())
}
pub fn close_orphan(id: &str) -> PlatformResult<()> {
    let Some(record) = read_record(id)? else { return Ok(()); };
    let Some(process) = windows::VerifiedProcess::open(&record, &kernel::executable(&record.kernel_version)?)? else { return Ok(()); };
    // The file is generated by this profile's Chromium, never supplied by React.
    let port_file = root()?.join("environments").join(id).join("DevToolsActivePort");
    if let Ok(text) = fs::read_to_string(port_file) {
        if text.len() < 1024 {
            let mut lines = text.lines();
            if let (Some(port), Some(path)) = (lines.next().and_then(|p|p.parse::<u16>().ok()), lines.next()) {
                if let Ok(mut connection) = super::cdp::Connection::connect(port,path) { connection.close(); }
            }
        }
    }
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(5);
    while process.alive()? && std::time::Instant::now() < deadline { std::thread::sleep(std::time::Duration::from_millis(100)); }
    if process.alive()? { process.terminate()?; }
    if process.alive()? { return Err(error("遗留浏览器尚未退出，请关闭对应窗口后重试")); }
    fs::remove_file(record_path(id)?).map_err(|_| error("浏览器已退出，但进程记录清理失败"))?;
    Ok(())
}
